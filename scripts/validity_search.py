"""Validity of thresholded rules (exp12): results/exp12_transfer/VALIDITY.md.

For each rule at the alarm threshold tuned in exp10 (paper Table IV), the
smallest level c of a unanimous honest neighbourhood whose thresholded output
is 0 (a miss): a camera of degree 4, own and 4 neighbours all honest and all
at true level c, each belief drawn from the belief bank among the beliefs of
class c that the detector gets right (ordinal median = c; the bank has no
belief above 0.5 confidence at levels 1-3, so "confident" means correct).
The thresholded output is 0 exactly when the alarm score is below tau.

Search per (rule, c), on the alarm score: (i) every correct belief repeated
five times; (ii) 20,000 random 5-tuples (with replacement); (iii) coordinate
descent from the lowest tuple of (i)-(ii): one camera at a time takes the
belief that lowers the score most, until no change.

Usage: python scripts/validity_search.py [--bank results/detector_base/ensemble/belief_bank.npz]
"""
import argparse
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from bflood.levels import ordinal_median  # noqa: E402
from bflood.rules import build_rule  # noqa: E402

RULES = [("unfiltered", {"rule": "unfiltered_mean"}, 0.75, "Unfiltered mean"),
         ("majority", {"rule": "majority"}, 0.85, "Majority vote"),
         ("coord_median", {"rule": "coord_median"}, 0.85, "Coordinate median"),
         ("wmsr_F2", {"rule": "wmsr", "F": 2}, 0.35, "W-MSR (F=2)"),
         ("bf_v1", {"rule": "bf_v1"}, 0.90, "Filtered temporal mean (FTM)"),
         ("oracle", {"rule": "oracle"}, 0.65, "Oracle (no Byzantine here)")]
N_RANDOM = 20000


def score_fn(spec):
    def f(tup):
        r = build_rule(spec)  # fresh: bf_v1 without history
        r.reset(None)
        if getattr(r, "needs_oracle", False):
            r.byz = set()
        own = r.payload_from_belief(tup[0])
        rec = {u: r.payload_from_belief(b) for u, b in enumerate(tup[1:], start=1)}
        return r.alarm_score(0, own, rec, 1), r.decide(0, own, rec, 1)[0]
    return f


def search(f, pool, rng):
    """Returns (min score, its tuple of pool indices, scores of the random tuples)."""
    best, best_idx = None, None
    for i in range(len(pool)):
        s, _ = f([pool[i]] * 5)
        if best is None or s < best:
            best, best_idx = s, [i] * 5
    scores = []
    for _ in range(N_RANDOM):
        idx = [int(i) for i in rng.integers(len(pool), size=5)]
        s, _ = f([pool[i] for i in idx])
        scores.append(s)
        if s < best:
            best, best_idx = s, idx
    changed = True
    while changed:
        changed = False
        for k in range(5):
            for i in range(len(pool)):
                trial = list(best_idx)
                trial[k] = i
                s, _ = f([pool[j] for j in trial])
                if s < best - 1e-12:
                    best, best_idx, changed = s, trial, True
    return best, best_idx, np.array(scores)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--bank", default=str(ROOT / "results/detector_base/ensemble/belief_bank.npz"))
    ap.add_argument("--out", default=str(ROOT / "results/exp12_transfer/VALIDITY.md"))
    a = ap.parse_args()
    d = np.load(a.bank)
    pools = {}
    for c in range(1, 5):
        P = d["probs"][d["labels"] == c]
        pools[c] = [p for p in P if ordinal_median(p) == c]
    L = ["# Validity of thresholded rules (unanimous honest neighbourhood)", "",
         "A camera of degree 4; own and 4 neighbours honest, all at true level c; beliefs drawn",
         "from the `detector_base` bank among the beliefs of class c that the detector gets right",
         "(ordinal median = c). Rules at the alarm threshold tuned in exp10 (paper Table IV); the",
         "thresholded output is 0 (a miss) exactly when the alarm score is below tau. Search per",
         f"(rule, c): every correct belief repeated five times, {N_RANDOM:,} random 5-tuples, then",
         "coordinate descent on the score. Generated by `scripts/validity_search.py`.", "",
         "Correct beliefs per level: " + ", ".join(f"c={c}: {len(pools[c])}" for c in pools)
         + " (of " + ", ".join(str(int((d['labels'] == c).sum())) for c in pools) + " bank beliefs).", "",
         "| Rule | tau | smallest c with output 0 | min score at that c | share of random tuples with output 0, c = 1 / 2 / 3 / 4 | p0 of the minimising tuple |",
         "|---|---|---|---|---|---|"]
    detail = ["", "Minimum alarm score per level (output 0 iff < tau):", "",
              "| Rule | tau | c = 1 | c = 2 | c = 3 | c = 4 |", "|---|---|---|---|---|---|"]
    rng = np.random.default_rng(2026)
    for key, spec, tau, name in RULES:
        f = score_fn(spec)
        mins, shares, ex = {}, {}, {}
        for c in range(1, 5):
            best, idx, scores = search(f, pools[c], rng)
            mins[c] = best
            shares[c] = float(np.mean(scores < tau))
            ex[c] = [round(float(pools[c][i][0]), 3) for i in idx]
        miss_c = [c for c in range(1, 5) if mins[c] < tau]
        c0 = miss_c[0] if miss_c else None
        L.append(f"| {name} | {tau:.2f} | {c0} | {mins[c0]:.3f} | " if c0
                 else f"| {name} | {tau:.2f} | none (c = 1-4) | - | ")
        L[-1] += " / ".join(f"{100 * shares[c]:.1f} %" for c in range(1, 5)) + " | "
        L[-1] += (", ".join(f"{x:.3f}" for x in ex[c0]) if c0 else "-") + " |"
        detail.append(f"| {name} | {tau:.2f} | " + " | ".join(f"{mins[c]:.3f}" for c in range(1, 5)) + " |")
        print(name, {c: round(mins[c], 3) for c in mins}, {c: round(shares[c], 3) for c in shares}, flush=True)
    bf = build_rule({"rule": "bf_v2"})
    bf.reset(None)
    outs = {c: min(bf.decide(0, p, {u: p for u in range(1, 5)}, 1)[0] for p in pools[c]) for c in pools}
    L.append("| ByzantineFlood (normal output) | -- | none (c = 1-4) | - | 0 % (output = c) | - |")
    L += detail + ["", "ByzantineFlood outputs the weighted median of the five levels, all equal to c, so its "
                   f"output is c for every such neighbourhood (checked: min output per c {outs})."]
    Path(a.out).parent.mkdir(parents=True, exist_ok=True)
    Path(a.out).write_text("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
