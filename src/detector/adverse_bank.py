"""Adverse belief bank (exp13, condition model, Oct 2026).

The detector ensemble of a run (fold*.pt) is applied to the images of its
belief bank (the exact-label rows of deepflood_test, fe8k_test and
alley_test, in the order of report.belief_bank) twice, on CPU in float32:

  normal   evaluation transform (letterbox), the reference on the same
           hardware (the stored bank was computed on GPU in bfloat16);
  adverse  transforms.adverse_transform: infrared night, rain streaks and
           lens droplets at full strength, then letterbox. Drop and streak
           positions are seeded per image ([2026, i]).

Writes <run>/ensemble/belief_bank_adverse.npz and belief_bank_cpu.npz (keys
labels, probs, source, member) and ADVERSE_BANK.md (accuracy per level).
"""
from __future__ import annotations

import csv
import time
from pathlib import Path

import numpy as np

from . import ordinal as O
from .io import ZipImageReader
from .transforms import adverse_transform, evaluate_transform

BANK_SETS = ("deepflood_test", "fe8k_test", "alley_test")  # report.belief_bank order
MEAN = np.array([0.485, 0.456, 0.406], np.float32)
STD = np.array([0.229, 0.224, 0.225], np.float32)


def _int(x, default=-1):
    return int(x) if str(x).strip() != "" else default


def bank_rows(manifest: Path):
    rows = list(csv.DictReader(open(manifest, encoding="utf-8")))
    out = []
    for s in BANK_SETS:
        for r in rows:
            if r["test_set"] == s and _int(r["level_lo"]) == _int(r["level_hi"]) >= 0:
                out.append(r)
    return out


def _tensor(x):
    import torch
    x = (x.astype(np.float32) / 255.0 - MEAN) / STD
    return torch.from_numpy(x.transpose(2, 0, 1).copy())


def per_level(probs, labels):
    lv = O.ordinal_level(probs)
    acc = {c: float((lv[labels == c] == c).mean()) for c in range(O.N_LEVELS)}
    conf = {c: float(probs[labels == c].max(1).mean()) for c in range(O.N_LEVELS)}
    return acc, conf, float((lv == labels).mean()), float((lv[labels == 0] >= 1).mean())


def run(data_dir: str, run_dir: str, batch: int = 16, threads: int = 8) -> str:
    import torch

    from .train import OrdinalNet

    torch.set_num_threads(threads)
    data_dir, run_dir = Path(data_dir), Path(run_dir)
    ens = run_dir / "ensemble"
    stored = np.load(ens / "belief_bank.npz")
    rows = bank_rows(data_dir / "processed" / "manifest.csv")
    labels = np.array([_int(r["level_lo"]) for r in rows])
    source = np.array([r["test_set"] for r in rows])
    if not (np.array_equal(labels, stored["labels"]) and np.array_equal(source, stored["source"])):
        raise RuntimeError("manifest rows do not match the stored belief bank")
    folds = sorted(run_dir.glob("fold*.pt"))
    models = []
    for f in folds:
        ck = torch.load(f, map_location="cpu", weights_only=False)
        m = OrdinalNet(pretrained=False)
        m.load_state_dict(ck["state_dict"])
        m.eval()
        models.append((m, float(ck["temperature"]), int(ck["config"]["size"])))
    size = models[0][2]
    reader = ZipImageReader(data_dir)
    probs = {"normal": np.zeros((len(rows), O.N_LEVELS)), "adverse": np.zeros((len(rows), O.N_LEVELS))}
    t0 = time.time()
    for b0 in range(0, len(rows), batch):
        idx = range(b0, min(len(rows), b0 + batch))
        xs = {"normal": [], "adverse": []}
        for i in idx:
            img = reader.read(rows[i]["zip"], rows[i]["member"])
            xs["normal"].append(_tensor(evaluate_transform(img, size)))
            xs["adverse"].append(_tensor(adverse_transform(img, np.random.default_rng([2026, i]), size)))
        for k in xs:
            x = torch.stack(xs[k])
            acc = np.zeros((len(idx), O.N_LEVELS))
            with torch.no_grad():
                for m, T, _ in models:
                    q = 1 / (1 + np.exp(-m(x).float().numpy() / T))
                    acc += O.beliefs_from_cum(q)
            probs[k][list(idx)] = acc / len(models)
        print(f"{b0 + len(idx)}/{len(rows)} images, {time.time() - t0:.0f}s", flush=True)
    member = np.array([r["member"] for r in rows])
    for k, name in (("normal", "belief_bank_cpu.npz"), ("adverse", "belief_bank_adverse.npz")):
        np.savez(ens / name, labels=labels, probs=probs[k], source=source, member=member)
    lines = ["# Adverse belief bank", "",
             f"{len(rows)} bank images ({', '.join(f'{s} {int((source == s).sum())}' for s in BANK_SETS)}),",
             f"ensemble of {len(models)} folds of `{run_dir.name}`, CPU float32. Adverse: infrared night +",
             "rain streaks + lens droplets at full strength (`transforms.adverse_transform`),",
             "positions seeded per image. Accuracy = ordinal median equals the label; FA = level-0",
             "images with ordinal median >= 1. Generated by `src/detector/adverse_bank.py`.", "",
             "| Bank | L0 | L1 | L2 | L3 | L4 | all | FA (L0) | mean confidence L0-L4 |",
             "|---|---|---|---|---|---|---|---|---|"]
    for name, p in (("stored (GPU bf16)", stored["probs"]), ("normal, CPU", probs["normal"]),
                    ("adverse, CPU", probs["adverse"])):
        a, c, tot, fa = per_level(p, labels)
        lines.append(f"| {name} | " + " | ".join(f"{a[k]:.3f}" for k in range(5))
                     + f" | {tot:.3f} | {fa:.3f} | " + " / ".join(f"{c[k]:.2f}" for k in range(5)) + " |")
    n = np.bincount(labels, minlength=5)
    d = np.abs(probs["normal"] - stored["probs"]).max()
    same = float((O.ordinal_level(probs["normal"]) == O.ordinal_level(stored["probs"])).mean())
    lines += ["", f"Images per level: {n.tolist()}. Normal CPU vs stored bank: max |dp| = {d:.4f}, "
              f"same ordinal level for {100 * same:.1f} % of images.", ""]
    md = "\n".join(lines) + "\n"
    (ens / "ADVERSE_BANK.md").write_text(md)
    return md
